// stats.js – Statistical exploration of the map k → kG.
// Uses the functions in curve.js. Charts use Chart.js (loaded from a CDN in stats.html).

const CURVES = {
  17: { p: 17, b: 7, G: { x: 1, y: 5 }, n: 9 },
  10007: { p: 10007, b: 7, G: { x: 5, y: 566 }, n: 10008 } // this G generates all 10008 points
};

const charts = {};

// ---------- helpers ----------
// Random k in [1, n-1] from the browser's cryptographic generator.
// (The modulo adds a negligible bias because n is much smaller than 2^32.)
function randomK(n) {
  const buf = new Uint32Array(1);
  crypto.getRandomValues(buf);
  return 1 + (buf[0] % (n - 1));
}

const bitLength = p => Math.ceil(Math.log2(p));
const popCount = v => v.toString(2).split("").filter(c => c === "1").length;
const mean = a => a.reduce((s, v) => s + v, 0) / a.length;

function pearson(a, b) {
  const ma = mean(a), mb = mean(b);
  let num = 0, da = 0, db = 0;
  for (let i = 0; i < a.length; i++) {
    num += (a[i] - ma) * (b[i] - mb);
    da += (a[i] - ma) ** 2;
    db += (b[i] - mb) ** 2;
  }
  return num / Math.sqrt(da * db);
}

// Chi-squared statistic: compares observed counts with expected counts.
function chiSquared(observed, expected) {
  let chi = 0;
  for (let i = 0; i < observed.length; i++) {
    if (expected[i] > 0) chi += (observed[i] - expected[i]) ** 2 / expected[i];
  }
  return chi;
}

function draw(id, config) {
  if (charts[id]) charts[id].destroy();
  config.options = Object.assign({ animation: false, plugins: { legend: { display: config.data.datasets.length > 1 } } }, config.options);
  charts[id] = new Chart(document.getElementById(id), config);
}

// Groups values 0..p-1 into equal-width bins.
function histogram(values, p, bins) {
  const counts = new Array(bins).fill(0);
  for (const v of values) counts[Math.min(bins - 1, Math.floor(v * bins / p))]++;
  return counts;
}

function text(id, s) {
  document.getElementById(id).textContent = s;
}

// ---------- experiments ----------
function run() {
  const curve = CURVES[document.getElementById("curve").value];
  const N = Math.max(100, Math.min(50000, Number(document.getElementById("samples").value) || 5000));
  const { p, n, G } = curve;
  const B = bitLength(p);
  const t0 = performance.now();

  // Sampling: N random private keys and their public keys.
  const ks = [], xs = [], ys = [];
  for (let i = 0; i < N; i++) {
    const k = randomK(n);
    const Q = scalarMult(k, G, curve).result;
    ks.push(k); xs.push(Q.x); ys.push(Q.y);
  }

  // Theoretical distribution: how many points of <G> have each x.
  const expectedPerX = new Array(p).fill(0);
  let Q = G;
  for (let i = 1; i < n; i++) { expectedPerX[Q.x]++; Q = add(Q, G, curve); }

  // 1. Distribution of x and y + chi-squared against the uniform distribution
  const bins = Math.min(p, 20);
  const hx = histogram(xs, p, bins), hy = histogram(ys, p, bins);
  const widths = Array.from({ length: bins }, (_, i) => Math.floor((i + 1) * p / bins) - Math.floor(i * p / bins));
  const uniform = widths.map(w => N * w / p);
  draw("c1", {
    type: "bar",
    data: {
      labels: widths.map((_, i) => `${Math.floor(i * p / bins)}–${Math.floor((i + 1) * p / bins) - 1}`),
      datasets: [
        { label: "x", data: hx },
        { label: "y", data: hy },
        { label: "expected if uniform", data: uniform, type: "line", pointRadius: 0 }
      ]
    }
  });
  text("r1", `Chi-squared vs uniform (${bins - 1} degrees of freedom): x = ${chiSquared(hx, uniform).toFixed(1)}, ` +
    `y = ${chiSquared(hy, uniform).toFixed(1)}. Values much larger than ${bins - 1} indicate non-uniformity.`);

  // 2. Frequency of individual x values, compared with the structure of the curve
  const freqX = new Array(p).fill(0);
  for (const x of xs) freqX[x]++;
  const impossible = expectedPerX.filter(c => c === 0).length;
  const unseen = freqX.filter(c => c === 0).length;
  const howMany = [0, 1, 2].map(m => expectedPerX.filter(c => c === m).length);
  const chiCurve = chiSquared(freqX, expectedPerX.map(c => c * N / (n - 1)));
  draw("c2", {
    type: "bar",
    data: { labels: ["0 points", "1 point", "2 points"], datasets: [{ label: "number of x values", data: howMany }] },
    options: { plugins: { legend: { display: false }, title: { display: true, text: "How many points of the group share a given x" } } }
  });
  text("r2", `${impossible} of ${p} x values (${(100 * impossible / p).toFixed(1)}%) can never appear: no point generated by G has that x (either x³ + 7 is not a square mod p, or the point is outside the subgroup of G). ` +
    `${unseen} values are missing from the sample (some possible ones were simply not drawn). ` +
    `Chi-squared vs the distribution expected from the curve: ${chiCurve.toFixed(1)} with about ${p - impossible - 1} degrees of freedom (close values mean agreement).`);

  // 3. Distribution of the bits of x
  const fractions = [];
  for (let b = 0; b < B; b++) fractions.push(mean(xs.map(x => (x >> b) & 1)));
  draw("c3", {
    type: "bar",
    data: {
      labels: fractions.map((_, b) => `bit ${b}`),
      datasets: [
        { label: "fraction of 1s", data: fractions },
        { label: "0.5", data: fractions.map(() => 0.5), type: "line", pointRadius: 0 }
      ]
    },
    options: { scales: { y: { min: 0, max: 1 } } }
  });
  text("r3", `Average fraction of 1 bits: ${mean(fractions).toFixed(3)}. ` +
    `The highest bits are unbalanced because p = ${p} is not a power of 2 (x < ${p} < 2^${B}).`);

  // 4. Input/output correlation
  const shown = Math.min(N, 2000);
  draw("c4", {
    type: "scatter",
    data: { datasets: [{ label: "(k, x of kG)", data: ks.slice(0, shown).map((k, i) => ({ x: k, y: xs[i] })), pointRadius: 2 }] },
    options: { scales: { x: { title: { display: true, text: "k" } }, y: { title: { display: true, text: "x of kG" } } } }
  });
  text("r4", `Pearson coefficient r = ${pearson(ks, xs).toFixed(4)} (0 = no linear correlation). Showing ${shown} points.`);

  // 5. Avalanche effect: flip one bit of k, how many bits of x change?
  const kBits = bitLength(n);
  const distances = [];
  const byPosition = Array.from({ length: kBits }, () => []);
  for (let i = 0; i < Math.min(N, 3000); i++) {
    const pos = i % kBits;
    const k2 = (ks[i] ^ (1 << pos)) % n;
    if (k2 === 0) continue;
    const d = popCount(xs[i] ^ scalarMult(k2, G, curve).result.x);
    distances.push(d);
    byPosition[pos].push(d / B);
  }
  const hd = new Array(B + 1).fill(0);
  for (const d of distances) hd[d]++;
  draw("c5", {
    type: "bar",
    data: { labels: hd.map((_, d) => d), datasets: [{ label: "cases", data: hd }] },
    options: { plugins: { legend: { display: false } }, scales: { x: { title: { display: true, text: `bits of x that changed (out of ${B})` } } } }
  });
  text("r5", `On average ${(100 * mean(distances) / B).toFixed(1)}% of the bits of x change (ideal for a hash: 50%). ` +
    `By flipped bit of k: ` + byPosition.map((a, i) => `${i}: ${(100 * mean(a)).toFixed(0)}%`).join(", ") + ".");

  // 6. Algebraic structure: k and n−k give the same x; the map is linear.
  let sameX = 0, linear = 0;
  const checks = Math.min(N, 2000);
  for (let i = 0; i < checks; i++) {
    const k1 = ks[i], k2 = ks[(i + 1) % N];
    const A = scalarMult(k1, G, curve).result;
    const M = scalarMult(n - k1, G, curve).result;
    if (A.x === M.x && A.y === mod(-M.y, p)) sameX++;
    const sum = add(A, scalarMult(k2, G, curve).result, curve);
    const direct = (k1 + k2) % n === 0 ? null : scalarMult((k1 + k2) % n, G, curve).result;
    if (equal(sum, direct)) linear++;
  }
  const upTo = Math.min(n - 1, 200);
  const xk = [], xMirror = [];
  for (let k = 1; k <= upTo; k++) {
    xk.push(scalarMult(k, G, curve).result.x);
    xMirror.push(scalarMult(n - k, G, curve).result.x);
  }
  draw("c6", {
    type: "line",
    data: {
      labels: xk.map((_, i) => i + 1),
      datasets: [
        { label: "x of kG", data: xk, pointRadius: 1.5, borderWidth: 1 },
        { label: "x of (n−k)G", data: xMirror, pointRadius: 0, borderWidth: 1, borderDash: [4, 3] }
      ]
    },
    options: { scales: { x: { title: { display: true, text: "k" } } } }
  });
  text("r6", `kG and (n−k)G have the same x (and opposite y) in ${sameX} of ${checks} cases. ` +
    `(k₁ + k₂)G = k₁G + k₂G in ${linear} of ${checks} cases: the map is a homomorphism, not a "random" function.`);

  text("summary", `Curve p = ${p}, G = ${format(G)}, order n = ${n}, ${N} samples, computed in ${(performance.now() - t0).toFixed(0)} ms.`);
}

document.getElementById("run").addEventListener("click", run);
run();